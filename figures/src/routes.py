"""
Draw the ablation bars for routes.tex: build/routes-<run>.tikz, one per seed.

Also writes the head names each seed's rows refer to, in build/routes-values.tex.

Each row is one intervention, its bar the copy accuracy on test sequences under it. Bars
where copying collapses (below half of the unablated accuracy) are spot. Layout only; the
numbers are data/ablations-*.csv and data/summary-*.json.
"""

import csv
import json

RUNS = ('default-seed0', 'default-seed1', 'default-seed2')
# Rows from the top; None leaves a gap between the two groups.
ROWS = (
  'none', 'identity', 'induction_heads', 'previous_head', 'duplicate_head', 'control_0', None,
  'previous_to_q', 'previous_to_k', 'previous_to_v',
  'duplicate_to_q', 'duplicate_to_k', 'duplicate_to_v',
  'control_to_q', 'control_to_k', 'control_to_v',
)
WIDTH, PITCH, BAR = 2.5, 0.36, 0.24  # cm for 100%, row spacing, bar thickness

values = ['% Generated by src/routes.py from data/; do not edit.']
for i, run in enumerate(RUNS):
  with open(f'data/ablations-{run}.csv') as f:
    rows = {r['condition']: r for r in csv.DictReader(f)}
  clean = float(rows['none']['copy_accuracy'])
  bottom = -(len(ROWS) - 1) * PITCH - PITCH / 2
  # The no-ablation line goes first, so the numbers' knockouts sit over it.
  out = [f'\\draw[level line] ({WIDTH * clean:.3f},{PITCH / 2:.3f}) -- ({WIDTH * clean:.3f},{bottom:.3f});']
  for slot, key in enumerate(ROWS):
    if key is None:
      continue
    y = -slot * PITCH
    accuracy = float(rows[key]['copy_accuracy'])
    colour = 'spot' if accuracy < clean / 2 else 'ink'
    length = WIDTH * accuracy
    out.append(f'\\draw[{colour}, line width=0.45pt, hatch={colour}!50] (0,{y - BAR / 2:.3f}) rectangle ({length:.3f},{y + BAR / 2:.3f});')
    out.append(f'\\node[font=\\scriptsize, text={colour}, anchor=west, knockout] at ({length + 0.06:.3f},{y:.3f}) {{{100 * accuracy:.0f}}};')
  out.append(f'\\draw[pbase] (0,{PITCH / 2:.3f}) -- (0,{bottom:.3f});')
  with open(f'build/routes-{run}.tikz', 'w') as f:
    f.write('\n'.join(out) + '\n')
  with open(f'data/summary-{run}.json') as f:
    heads = json.load(f)['heads']
  tag = 'ABC'[i]
  name = lambda pair: f'{pair[0]}.{pair[1]}'  # noqa: E731
  values.append(
    f'\\def\\routesPrev{tag}{{{name(heads["previous-token"])}}}'
    f'\\def\\routesDup{tag}{{{name(heads["duplicate-token"])}}}'
    f'\\def\\routesControl{tag}{{{name(heads["layer-0 control"])}}}'
  )
with open('build/routes-values.tex', 'w') as f:
  f.write('\n'.join(values) + '\n')
