"""
Write build/values.tex: the numbers the figures quote, as macros, read from data/.

Per seed: the phase-change step, final copy accuracy and the heads in each role; for the
baselines, final copy accuracy; and chance. Formatting only.
"""

import json

SEEDS = {'A': 'default-seed0', 'B': 'default-seed1', 'C': 'default-seed2'}
BASELINES = {'OneLayer': 'one-layer-seed0', 'GptInit': 'gpt2-init-seed0'}
lines = ['% Generated by src/values.py from data/; do not edit.']


def summary(run: str) -> dict:
  with open(f'data/summary-{run}.json') as f:
    return json.load(f)


def head(pair: list[int]) -> str:
  return f'{pair[0]}.{pair[1]}'


for tag, run in SEEDS.items():
  s = summary(run)
  lines.append(
    f'\\def\\phase{tag}{{{s["phase_change_step"]}}}'
    f'\\def\\copy{tag}{{{100 * s["trained"]["copy_accuracy"]:.0f}}}'
    f'\\def\\prev{tag}{{{head(s["heads"]["previous-token"])}}}'
    f'\\def\\dup{tag}{{{head(s["heads"]["duplicate-token"])}}}'
  )
for tag, run in BASELINES.items():
  s = summary(run)
  lines.append(f'\\def\\copy{tag}{{{100 * s["trained"]["copy_accuracy"]:.0f}}}')
chance = summary(SEEDS['A'])['chance']
lines.append(f'\\def\\chanceloss{{{chance["loss"]:.2f}}}\\def\\steps{{{summary(SEEDS["A"])["steps"]}}}')

with open('build/values.tex', 'w') as f:
  f.write('\n'.join(lines) + '\n')

# The TinyStories run: final scores of its previous-token and nascent induction heads.
s = summary('stories-seed0')
with open('data/curves-stories-seed0.csv') as f:
  last = f.read().strip().splitlines()[-1].split(',')
with open('data/curves-stories-seed0.csv') as f:
  header = f.readline().strip().split(',')
final = dict(zip(header, last, strict=True))
with open('build/values.tex', 'a') as f:
  f.write(
    f'\\def\\storyPrev{{{head(s["heads"]["previous-token"])}}}\\def\\storyInd{{{head(s["heads"]["induction"])}}}'
    f'\\def\\storyPrevScore{{{float(final["previous"]):.2f}}}\\def\\storyIndScore{{{float(final["induction"]):.2f}}}'
    f'\\def\\storyIcl{{{float(final["icl_score"]):.2f}}}\\def\\storyLoss{{{float(final["text_loss"]):.2f}}}\n'
  )
